const line = (e: PlaybookEntry) => `- ${e.when} → ${e.fixed ? `בדיוק: "${e.answer}"` : e.answer}`;

/** The playbook section of the system prompt (stable text). */
export function renderPlaybook(): string {
  return [
    "# playbook של אור (בסיס לתשובה, מתאימים לשיחה ולא מעתיקים מילה במילה, חוץ מ\"בדיוק\")",
    "## התנגדויות",
    ...OBJECTIONS.map(line),
    "## גבולות מקצועיים",
    ...BOUNDARIES.map(line),
    "## תמיד",
    ...ALWAYS.map((a) => `- ${a}`),
    "## לעולם לא",
    ...NEVER.map((n) => `- ${n}`),
  ].join("\n");
}
